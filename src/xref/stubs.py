"""Render a published manifest as a dbt package of ephemeral stub models.

Each public model becomes `select * from <relation>`, so
`ref('producer', 'model')` in the consumer compiles to a CTE over the
producer's table. The YAML carries descriptions, columns and versions.
It deliberately carries no data tests (they would rerun the producer's tests
in every consumer build) and no contracts (dbt does not enforce them on
ephemeral models).
"""

from __future__ import annotations

from itertools import groupby
from pathlib import PurePosixPath
from typing import Any

import yaml

from xref.published import PublishedManifest, PublishedModel

MODELS_YAML = PurePosixPath("models/_xref_models.yml")


def render_stub_package(published: PublishedManifest) -> dict[PurePosixPath, str]:
    header = (
        f"# Generated by xref from {published.project_name} ({published.environment}), "
        f"dbt manifest generated at {published.generated_at}.\n"
        "# Do not edit: `xref sync` overwrites this package.\n"
    )
    files: dict[PurePosixPath, str] = {
        PurePosixPath("dbt_project.yml"): header
        + _dump(
            {
                "name": published.project_name,
                "version": "1.0.0",
                "config-version": 2,
                "model-paths": ["models"],
            }
        ),
    }

    entries: list[dict[str, Any]] = []
    for name, group in groupby(published.models, key=lambda m: m.name):
        versions = list(group)
        for model in versions:
            files[PurePosixPath("models") / f"{model.file_stem}.sql"] = _sql(model, header)
        entries.append(_yaml_entry(name, versions))

    files[MODELS_YAML] = header + _dump({"models": entries})
    return files


def _sql(model: PublishedModel, header: str) -> str:
    comment = "".join(f"-- {line.removeprefix('# ')}\n" for line in header.splitlines())
    return f"{comment}{{{{ config(materialized='ephemeral') }}}}\nselect * from {model.relation_name}\n"


def _yaml_entry(name: str, versions: list[PublishedModel]) -> dict[str, Any]:
    unversioned = len(versions) == 1 and versions[0].version is None
    if unversioned:
        doc_source = versions[0]
    else:
        latest = versions[0].latest_version
        doc_source = next((v for v in versions if v.version == latest), versions[-1])

    entry: dict[str, Any] = {"name": name}
    if doc_source.description:
        entry["description"] = _jinja_safe(doc_source.description)
    if not unversioned and doc_source.latest_version is not None:
        entry["latest_version"] = doc_source.latest_version
    entry["config"] = {"access": "public"}
    if not unversioned:
        entry["versions"] = [_version_entry(v) for v in versions]
    if doc_source.columns:
        entry["columns"] = [
            _column_entry(c.name, c.description, c.data_type) for c in doc_source.columns
        ]
    return entry


def _version_entry(model: PublishedModel) -> dict[str, Any]:
    entry: dict[str, Any] = {"v": model.version}
    if model.deprecation_date:
        entry["deprecation_date"] = model.deprecation_date
    return entry


def _column_entry(name: str, description: str, data_type: str | None) -> dict[str, Any]:
    entry: dict[str, Any] = {"name": name}
    if description:
        entry["description"] = _jinja_safe(description)
    if data_type:
        entry["data_type"] = data_type
    return entry


def _jinja_safe(text: str) -> str:
    """dbt renders descriptions as Jinja. The producer's are already rendered, so
    any braces left in them are literal text and must not be evaluated again."""
    if "{{" in text or "{%" in text or "{#" in text:
        return "{% raw %}" + text.replace("{% endraw %}", "") + "{% endraw %}"
    return text


def _dump(data: dict[str, Any]) -> str:
    return yaml.safe_dump(
        data, sort_keys=False, default_flow_style=False, allow_unicode=True, width=1000
    )
